begin;

create type public.place_submission_status as enum (
  'pending',
  'changes_requested',
  'approved',
  'rejected'
);

create table public.app_user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin', 'moderator')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.place_submissions (
  id uuid primary key default gen_random_uuid(),
  submitted_by uuid not null references auth.users(id) on delete cascade,
  category_id bigint not null references public.categories(id)
    on update cascade on delete restrict,
  name text not null check (char_length(btrim(name)) between 3 and 80),
  description text not null
    check (char_length(btrim(description)) between 20 and 500),
  city text not null check (char_length(btrim(city)) between 2 and 80),
  district text,
  location_label text,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  environment_tags text[] not null default '{}',
  features text[] not null default '{}',
  road_access text,
  photo_paths text[] not null default '{}',
  status public.place_submission_status not null default 'pending',
  content_flags jsonb not null default '[]'::jsonb,
  moderator_note text,
  moderated_by uuid references auth.users(id) on delete set null,
  moderated_at timestamptz,
  published_place_id bigint references public.places(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index place_submissions_status_created_idx
  on public.place_submissions (status, created_at desc);
create index place_submissions_owner_created_idx
  on public.place_submissions (submitted_by, created_at desc);
create index place_submissions_coordinates_idx
  on public.place_submissions (latitude, longitude);

create table public.moderation_audit_logs (
  id bigint generated by default as identity primary key,
  submission_id uuid not null references public.place_submissions(id)
    on delete cascade,
  actor_id uuid not null references auth.users(id) on delete restrict,
  action text not null check (
    action in ('approve', 'reject', 'request_changes', 'resubmit')
  ),
  previous_status public.place_submission_status,
  new_status public.place_submission_status not null,
  note text,
  created_at timestamptz not null default now()
);

create or replace function public.is_place_moderator()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.app_user_roles
    where user_id = auth.uid()
      and role in ('admin', 'moderator')
  );
$$;

revoke all on function public.is_place_moderator() from public;
grant execute on function public.is_place_moderator() to authenticated;

alter table public.app_user_roles enable row level security;
alter table public.place_submissions enable row level security;
alter table public.moderation_audit_logs enable row level security;

create policy "Users can read their own role"
on public.app_user_roles for select
to authenticated
using (user_id = auth.uid() or public.is_place_moderator());

create policy "Authenticated users can create place submissions"
on public.place_submissions for insert
to authenticated
with check (
  submitted_by = auth.uid()
  and status = 'pending'
  and moderated_by is null
  and moderated_at is null
  and published_place_id is null
);

create policy "Users can read their own submissions"
on public.place_submissions for select
to authenticated
using (submitted_by = auth.uid() or public.is_place_moderator());

create policy "Moderators can update submissions"
on public.place_submissions for update
to authenticated
using (public.is_place_moderator())
with check (public.is_place_moderator());

create policy "Moderators can read moderation logs"
on public.moderation_audit_logs for select
to authenticated
using (public.is_place_moderator());

drop policy if exists "Places are publicly readable" on public.places;
create policy "Verified active places are publicly readable"
on public.places for select
to anon, authenticated
using (is_active = true and is_verified = true);

create or replace function public.review_place_submission(
  p_submission_id uuid,
  p_decision public.place_submission_status,
  p_note text default null
)
returns public.place_submissions
language plpgsql
security definer
set search_path = public
as $$
declare
  v_submission public.place_submissions;
  v_previous public.place_submission_status;
  v_action text;
begin
  if not public.is_place_moderator() then
    raise exception 'moderator permission required';
  end if;

  if p_decision not in ('rejected', 'changes_requested') then
    raise exception 'decision must be rejected or changes_requested';
  end if;

  select * into v_submission
  from public.place_submissions
  where id = p_submission_id
  for update;

  if not found then raise exception 'submission not found'; end if;
  if v_submission.status not in ('pending', 'changes_requested') then
    raise exception 'submission is already finalized';
  end if;

  v_previous := v_submission.status;
  v_action := case
    when p_decision = 'rejected' then 'reject'
    else 'request_changes'
  end;

  update public.place_submissions
  set status = p_decision,
      moderator_note = nullif(btrim(p_note), ''),
      moderated_by = auth.uid(),
      moderated_at = now(),
      updated_at = now()
  where id = p_submission_id
  returning * into v_submission;

  insert into public.moderation_audit_logs (
    submission_id, actor_id, action, previous_status, new_status, note
  ) values (
    p_submission_id, auth.uid(), v_action, v_previous, p_decision,
    nullif(btrim(p_note), '')
  );

  return v_submission;
end;
$$;

create or replace function public.approve_place_submission(
  p_submission_id uuid,
  p_note text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_submission public.place_submissions;
  v_place_id bigint;
  v_slug text;
begin
  if not public.is_place_moderator() then
    raise exception 'moderator permission required';
  end if;

  select * into v_submission
  from public.place_submissions
  where id = p_submission_id
  for update;

  if not found then raise exception 'submission not found'; end if;
  if v_submission.status not in ('pending', 'changes_requested') then
    raise exception 'submission is already finalized';
  end if;

  v_slug := 'community-' || replace(v_submission.id::text, '-', '');

  insert into public.places (
    category_id, name, slug, short_description, description,
    city, district, address, latitude, longitude,
    is_verified, last_verified_at, is_active
  ) values (
    v_submission.category_id,
    btrim(v_submission.name),
    v_slug,
    left(btrim(v_submission.description), 180),
    btrim(v_submission.description),
    btrim(v_submission.city),
    nullif(btrim(v_submission.district), ''),
    nullif(btrim(v_submission.location_label), ''),
    v_submission.latitude,
    v_submission.longitude,
    true,
    now(),
    true
  ) returning id into v_place_id;

  update public.place_submissions
  set status = 'approved',
      published_place_id = v_place_id,
      moderator_note = nullif(btrim(p_note), ''),
      moderated_by = auth.uid(),
      moderated_at = now(),
      updated_at = now()
  where id = p_submission_id;

  insert into public.moderation_audit_logs (
    submission_id, actor_id, action, previous_status, new_status, note
  ) values (
    p_submission_id, auth.uid(), 'approve', v_submission.status, 'approved',
    nullif(btrim(p_note), '')
  );

  return v_place_id;
end;
$$;

revoke all on function public.review_place_submission(
  uuid, public.place_submission_status, text
) from public;
revoke all on function public.approve_place_submission(uuid, text) from public;
grant execute on function public.review_place_submission(
  uuid, public.place_submission_status, text
) to authenticated;
grant execute on function public.approve_place_submission(uuid, text)
  to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'place-submissions',
  'place-submissions',
  false,
  8388608,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do nothing;

create policy "Users upload their own submission photos"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'place-submissions'
  and (storage.foldername(name))[1] = auth.uid()::text
);

create policy "Users and moderators read submission photos"
on storage.objects for select
to authenticated
using (
  bucket_id = 'place-submissions'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_place_moderator()
  )
);

create policy "Moderators manage submission photos"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'place-submissions'
  and public.is_place_moderator()
);

commit;
